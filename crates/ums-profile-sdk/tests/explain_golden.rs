#[test]
fn selected_not_first_but_not_the_incumbent_is_not_an_override() {
    // Tick 13 (record 5): selected engage at rank 2, but the incumbent is now
    // advance. The validator refuses this as UnexplainedSelection; the lens
    // must still not call it commitment. Tick 14 remains an override.
    let mut trace = fixture("mind-trace.json");
    trace["ticks"][5]["conation"]["incumbent"] = json!("advance");
    let report = explain(&fixture("runner-output.json"), Some(&trace), false).unwrap();
    let a = agent(&report, "agent-a");
    assert_eq!(a["commitment_override_ticks"], 1);
    assert_eq!(a["commitment_override_at"], json!([14]));
    let tick_13 = a["windows"]
        .as_array()
        .unwrap()
        .iter()
        .find(|window| window["first_tick"] == 13)
        .expect("tick 13 window");
    assert_eq!(tick_13["commitment_override"], false);
}

