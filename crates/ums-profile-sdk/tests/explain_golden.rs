//! The explain lens for `enaction-runner-output/1` plus
//! `enaction-mind-trace/1`: golden report, commitment override, belief
//! divergence under the closed-world rule (CAC-KERNEL section 9) and the
//! deferred leak verdict. The fixtures have the real document shapes:
//! propositions are opaque strings, a belief has a `bearer` and an
//! interval `confidence`, statuses are lowercase.
//!
//! The golden files are compared byte for byte. There is no bless mode: a
//! changed report is regenerated by hand and reviewed.

use serde_json::{Value, json};
use std::path::{Path, PathBuf};
use std::process::Command;
use ums_profile_sdk::canonical::to_canonical_string;
use ums_profile_sdk::explain::{ExplainError, LEAK_VERDICT, REPORT_CONTRACT, explain, render_text};

fn fixture_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/explain")
        .join(name)
}

fn fixture(name: &str) -> Value {
    let text = std::fs::read_to_string(fixture_path(name)).expect("fixture");
    serde_json::from_str(&text).expect("fixture JSON")
}

fn golden(name: &str) -> String {
    std::fs::read_to_string(fixture_path(name)).expect("golden file")
}

fn report(trace: &str) -> Value {
    explain(&fixture("runner-output.json"), Some(&fixture(trace)), false).expect("report")
}

fn agent<'a>(report: &'a Value, id: &str) -> &'a Value {
    report["agents"]
        .as_array()
        .expect("agents")
        .iter()
        .find(|agent| agent["agent"] == id)
        .unwrap_or_else(|| panic!("agent {id} in report"))
}

