#[test]
fn a_held_belief_absent_from_world_truth_diverges() {
    // World truth is closed over the stated propositions (CAC-KERNEL
    // section 9): "door is north" is stated (event 17) and absent, so it is
    // false in this world. Beliefs 1 (believed) and 4 (suspected) diverge.
    let report = report("mind-trace.json");
    let one = belief(&report, "agent-a", 1);
    assert_eq!(one["world"], "diverges-from-world");
    assert_eq!(one["in_world_truth"], false);
    assert_eq!(one["proposition"], "door is north");
    assert_eq!(
        one["confidence"],
        json!({"belief": 8000, "plausibility": 9500})
    );
    assert_eq!(
        belief(&report, "agent-b", 4)["world"],
        "diverges-from-world"
    );
}

