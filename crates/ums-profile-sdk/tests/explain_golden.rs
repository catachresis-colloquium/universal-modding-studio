#[test]
fn affect_changes_carry_their_resolved_causes() {
    let report = report("mind-trace.json");
    let windows = agent(&report, "agent-a")["windows"]
        .as_array()
        .unwrap()
        .clone();
    assert_eq!(windows[0]["affect"]["change"], "initial");
    // Tick 12: calm -> angry, caused by event 12 (an ActionOutcome).
    let angry = &windows[1];
    assert_eq!(angry["first_tick"], 12);
    assert_eq!(angry["affect"]["change"], "changed");
    assert_eq!(angry["affect"]["previous"], "calm");
    assert_eq!(
        angry["affect"]["caused_by"],
        json!([{"id": 12, "resolved": true, "kind": "action_outcome", "tick": 12}])
    );
    // Tick 13 starts a new window (the ranking changed) without a token change.
    assert_eq!(windows[2]["affect"]["change"], "unchanged");
}

